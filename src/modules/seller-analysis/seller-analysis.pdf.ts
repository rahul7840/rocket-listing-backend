import { readFileSync } from 'fs';
import { join } from 'path';
// eslint-disable-next-line @typescript-eslint/no-require-imports
import PDFDocument = require('pdfkit');
import {
  compact,
  Range,
  ReportModel,
  rupees,
  rupeesCompact,
} from './seller-analysis.report';

const ASSETS = join(__dirname, 'assets');
const FONT = {
  regular: join(ASSETS, 'fonts', 'inter-400.ttf'),
  medium: join(ASSETS, 'fonts', 'inter-500.ttf'),
  semibold: join(ASSETS, 'fonts', 'inter-600.ttf'),
  bold: join(ASSETS, 'fonts', 'inter-700.ttf'),
};

/** The extension's palette, so the report reads as the same product. */
const COLOR = {
  brand: '#6c5ce7',
  brandDark: '#4a3fb8',
  ink: '#18181b',
  body: '#52525b',
  muted: '#8a8a93',
  line: '#e4defa',
  hair: '#ececf2',
  panel: '#f7f5ff',
  tint: '#f1efff',
  track: '#efecff',
  good: '#26805a',
  goodTint: '#eaf6ef',
  warn: '#d97757',
};

export const SITE_URL = 'www.rocketlisting.in';
const SITE_LINK = 'https://www.rocketlisting.in';

/** What stands in for anything the report could not work out or was not given. */
export const NA = 'N/A';

/** How everything the algorithm estimates or suggests is credited in the report. */
const RL_ESTIMATE = 'RL algorithm estimate';
const RL_SUGGESTED = 'RL algorithm suggested';

const PAGE = { w: 595.28, h: 841.89, margin: 44 };
const CONTENT_W = PAGE.w - PAGE.margin * 2;
/** Content must end above the footer; a section that would cross this moves whole to the next page. */
const LIMIT = PAGE.h - 68;

export interface PdfAssets {
  /** The product photo as JPEG or PNG bytes (PDFKit cannot embed WebP) */
  image?: Buffer;
}

let logoCache: Buffer | undefined;
const logo = (): Buffer =>
  (logoCache ??= readFileSync(join(ASSETS, 'logo.png')));

type Doc = InstanceType<typeof PDFDocument>;
type FontKey = 'r' | 'm' | 's' | 'b';

export const FOOTER_NOTE =
  'Figures are estimates generated by the Rocket Listing algorithm from public ratings and listing data. Actual sales and earnings may differ.';

export function renderReportPdf(
  model: ReportModel,
  assets: PdfAssets = {},
): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({
      size: 'A4',
      margin: 0,
      bufferPages: true,
      info: {
        Title: `Seller analysis - ${model.title}`,
        Author: 'Rocket Listing',
        Creator: 'Rocket Listing',
      },
    });
    const chunks: Buffer[] = [];
    doc.on('data', (c: Buffer) => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    try {
      draw(doc, model, assets);
      doc.end();
    } catch (error) {
      reject(error);
    }
  });
}

function draw(doc: Doc, m: ReportModel, assets: PdfAssets): void {
  doc.registerFont('r', FONT.regular);
  doc.registerFont('m', FONT.medium);
  doc.registerFont('s', FONT.semibold);
  doc.registerFont('b', FONT.bold);

  const X = PAGE.margin;
  let y = 0;

  // ── drawing helpers ──────────────────────────────────────────────────────
  const text = (
    value: string,
    x: number,
    ty: number,
    font: FontKey,
    size: number,
    color: string,
    options: PDFKit.Mixins.TextOptions = {},
  ): void => {
    doc
      .font(font)
      .fontSize(size)
      .fillColor(color)
      .text(value, x, ty, { lineBreak: false, ...options });
  };
  const widthOf = (value: string, font: FontKey, size: number): number =>
    doc.font(font).fontSize(size).widthOfString(value);
  const heightOf = (
    value: string,
    font: FontKey,
    size: number,
    width: number,
    lineGap = 0,
  ): number =>
    doc.font(font).fontSize(size).heightOfString(value, { width, lineGap });
  const caps = (
    value: string,
    x: number,
    ty: number,
    color: string = COLOR.muted,
    options: PDFKit.Mixins.TextOptions = {},
  ): void =>
    text(value.toUpperCase(), x, ty, 's', 6.8, color, {
      characterSpacing: 0.9,
      ...options,
    });
  const hline = (
    x1: number,
    x2: number,
    ly: number,
    color: string = COLOR.hair,
  ): void => {
    doc
      .moveTo(x1, ly)
      .lineTo(x2, ly)
      .lineWidth(0.6)
      .strokeColor(color)
      .stroke();
  };
  const pill = (
    value: string,
    x: number,
    py: number,
    fg: string,
    bg: string,
    size = 7.6,
  ): number => {
    const w = widthOf(value, 's', size) + 12;
    doc.save();
    doc.roundedRect(x, py, w, 14, 7).fill(bg);
    doc.restore();
    text(value, x + 6, py + 3.6, 's', size, fg);
    return w;
  };
  const range = (r: Range | undefined, money: boolean): string | undefined =>
    r
      ? `${money ? rupeesCompact(r.low) : compact(r.low)} – ${money ? rupeesCompact(r.high) : compact(r.high)}`
      : undefined;
  const star = (cx: number, cy: number, r: number, color: string): void => {
    const points: Array<[number, number]> = [];
    for (let i = 0; i < 10; i += 1) {
      const radius = i % 2 === 0 ? r : r * 0.42;
      const angle = -Math.PI / 2 + (i * Math.PI) / 5;
      points.push([
        cx + radius * Math.cos(angle),
        cy + radius * Math.sin(angle),
      ]);
    }
    doc.save();
    doc.polygon(...points).fill(color);
    doc.restore();
  };

  /** Section title in small caps with a hairline running to the margin; `right` is a quiet caption at the end. */
  const heading = (title: string, right?: string): void => {
    caps(title, X, y, COLOR.brand);
    const tw = widthOf(title.toUpperCase(), 's', 6.8) + title.length * 0.9;
    let lineEnd = X + CONTENT_W;
    if (right) {
      const rw = widthOf(right.toUpperCase(), 's', 6.8) + right.length * 0.9;
      caps(right, X + CONTENT_W - rw, y, COLOR.muted);
      lineEnd -= rw + 10;
    }
    hline(X + tw + 10, lineEnd, y + 3.4, COLOR.line);
    y += 17;
  };

  const header = (): void => {
    doc.image(logo(), X, 32, { width: 22, height: 22 });
    text('Rocket Listing', X + 30, 36.5, 'b', 12, COLOR.ink);
    const uw = widthOf(SITE_URL, 'm', 8.5);
    text(SITE_URL, X + CONTENT_W - uw, 38, 'm', 8.5, COLOR.brand);
    doc.link(X + CONTENT_W - uw, 36, uw, 12, SITE_LINK);
    hline(X, X + CONTENT_W, 64, COLOR.line);
    y = 72;
  };

  /** Starts a new page (with the same header) unless `needed` points still fit; a section is never split. */
  const ensure = (needed: number): void => {
    if (y + needed <= LIMIT) return;
    doc.addPage();
    header();
  };

  header();

  // ── title row + product link ─────────────────────────────────────────────
  caps('Seller analysis', X, y + 5, COLOR.brand);
  if (m.productUrl) {
    const label = 'View product on Meesho';
    const w = widthOf(label, 's', 7.8) + 26;
    const bx = X + CONTENT_W - w;
    doc.save();
    doc.roundedRect(bx, y, w, 20, 10).lineWidth(0.8).stroke(COLOR.brand);
    doc.restore();
    text(label, bx + 13, y + 6.3, 's', 7.8, COLOR.brand);
    doc.link(bx, y, w, 20, m.productUrl);
  }
  y += 30;

  // ── product ──────────────────────────────────────────────────────────────
  const photo = 76;
  /** Height of the whole product block: name (2 lines), category path (2 lines) and the facts row sit beside the photo. */
  const productH = 92;
  doc.save();
  doc.roundedRect(X, y, photo, photo, 8).fillAndStroke('#ffffff', COLOR.line);
  doc.restore();
  if (assets.image) {
    doc.save();
    doc.roundedRect(X + 1, y + 1, photo - 2, photo - 2, 7).clip();
    doc.image(assets.image, X + 1, y + 1, {
      fit: [photo - 2, photo - 2],
      align: 'center',
      valign: 'center',
    });
    doc.restore();
  } else {
    text(NA, X, y + photo / 2 - 5, 'm', 9, COLOR.muted, {
      width: photo,
      align: 'center',
    });
  }

  const tx = X + photo + 20;
  const tw = CONTENT_W - photo - 20;
  const nameH = Math.min(heightOf(m.title, 'b', 12.5, tw, 1), 32);
  doc.font('b').fontSize(12.5).fillColor(COLOR.ink).text(m.title, tx, y, {
    width: tw,
    height: 32,
    ellipsis: true,
    lineGap: 1,
  });
  doc
    .font('r')
    .fontSize(8.3)
    .fillColor(m.categoryPath.length > 0 ? COLOR.body : COLOR.muted)
    .text(
      m.categoryPath.length > 0
        ? m.categoryPath.join('  ›  ')
        : `Category: ${NA}`,
      tx,
      y + nameH + 6,
      { width: tw, height: 22, ellipsis: true, lineGap: 2 },
    );

  const facts: Array<{ k: string; v: string; sub?: string }> = [
    { k: 'Sold from', v: m.soldFrom ?? NA },
    {
      k: 'Listing age',
      v: m.listed?.age ?? NA,
      sub: m.listed ? `since ${m.listed.since}` : undefined,
    },
    {
      k: 'Rating',
      v:
        m.rating?.average !== undefined
          ? `${m.rating.average.toFixed(1)} / 5`
          : NA,
      sub: m.rating
        ? `${m.rating.count.toLocaleString('en-IN')} ratings`
        : undefined,
    },
  ];
  const colW = tw / facts.length;
  facts.forEach((f, i) => {
    const fx = tx + i * colW;
    caps(f.k, fx, y + productH - 32);
    text(
      f.v,
      fx,
      y + productH - 22,
      's',
      9.5,
      f.v === NA ? COLOR.muted : COLOR.ink,
      {
        width: colW - 8,
        ellipsis: true,
      },
    );
    if (f.sub)
      text(f.sub, fx, y + productH - 9, 'r', 7.4, COLOR.muted, {
        width: colW - 8,
      });
  });
  y += productH + 16;

  // ── pricing ──────────────────────────────────────────────────────────────
  {
    const inputs =
      m.priceInputs.length > 0
        ? m.priceInputs
        : [
            'Customer price',
            'Catalog price',
            'Original price',
            'Prepaid offer',
          ].map((label) => ({ label, value: NA }));
    const panelH = 64 + inputs.length * 11 + 16;
    const blockH = Math.max(panelH, 80);
    ensure(17 + blockH);
    heading('Pricing');

    // Customer price: plain, no box.
    caps('Customer price', X, y);
    if (m.price) {
      const big = rupees(m.price.current);
      text(big, X, y + 13, 'b', 22, COLOR.ink);
      if (m.price.original !== undefined) {
        const ox = X + widthOf(big, 'b', 22) + 9;
        const original = rupees(m.price.original);
        text(original, ox, y + 22, 'r', 10, COLOR.muted);
        hline(ox, ox + widthOf(original, 'r', 10), y + 28.5, COLOR.muted);
      }
      let ry = y + 50;
      let rx = X;
      if (m.price.discountPct !== undefined && m.price.discountPct > 0) {
        rx +=
          pill(
            `${m.price.discountPct}% off`,
            rx,
            ry,
            COLOR.good,
            COLOR.goodTint,
          ) + 8;
      }
      if (m.price.withOffer !== undefined) {
        text(
          `${rupees(m.price.withOffer)} with prepaid offer`,
          rx,
          ry + 3.2,
          'm',
          8.2,
          COLOR.good,
        );
      }
      if (m.price.original !== undefined) {
        ry += 22;
        text(
          `Customers save ${rupees(m.price.original - m.price.current)} against the original price`,
          X,
          ry,
          'r',
          7.8,
          COLOR.muted,
        );
      }
    } else {
      text(NA, X, y + 13, 'b', 22, COLOR.muted);
    }

    // Estimated seller price: the one tinted panel, with the values it comes from underneath.
    const px = X + 262;
    const pw = CONTENT_W - 262;
    doc.save();
    doc
      .roundedRect(px, y - 4, pw, panelH, 8)
      .fillAndStroke(COLOR.panel, COLOR.line);
    doc.restore();
    caps('RL-estimated seller price', px + 14, y + 8, COLOR.brandDark);
    text(
      m.sellerPrice ? rupees(m.sellerPrice.mid) : NA,
      px + 14,
      y + 21,
      'b',
      22,
      m.sellerPrice ? COLOR.brandDark : COLOR.muted,
    );
    text(
      m.sellerPrice
        ? `Range ${rupees(m.sellerPrice.low)} – ${rupees(m.sellerPrice.high)}`
        : NA,
      px + 14,
      y + 48,
      'm',
      8.2,
      COLOR.body,
    );
    hline(px + 14, px + pw - 14, y + 63, COLOR.line);
    inputs.forEach((row, i) => {
      const ly = y + 70 + i * 11;
      text(row.label, px + 14, ly, 'r', 7.8, COLOR.body);
      text(
        row.value,
        px + 14,
        ly,
        's',
        7.8,
        row.value === NA ? COLOR.muted : COLOR.ink,
        {
          width: pw - 28,
          align: 'right',
        },
      );
    });
    y += blockH + 18;
  }

  // ── estimated sales ──────────────────────────────────────────────────────
  {
    ensure(17 + 2 + 46);
    heading(
      'Estimated sales',
      m.sales && m.sales.returnRatePct > 0
        ? `${RL_ESTIMATE} · after ${m.sales.returnRatePct}% returns`
        : RL_ESTIMATE,
    );
    y += 2;

    const monthly = m.sales?.monthly;
    const noMonthly =
      m.sales && !monthly && m.listed ? 'Listed too recently' : NA;
    const cells: Array<{ k: string; v?: string; r?: string; note: string }> = [
      {
        k: 'Lifetime orders',
        v: m.sales ? compact(m.sales.lifetimeOrders) : undefined,
        r: range(m.sales?.lifetimeOrdersRange, false),
        note: NA,
      },
      {
        k: 'Lifetime sales',
        v:
          m.sales?.lifetimeSales !== undefined
            ? rupeesCompact(m.sales.lifetimeSales)
            : undefined,
        r: range(m.sales?.lifetimeSalesRange, true),
        note: NA,
      },
      {
        k: 'Orders / month',
        v: monthly ? compact(monthly.orders) : undefined,
        r: monthly ? range(monthly.ordersRange, false) : undefined,
        note: noMonthly,
      },
      {
        k: 'Sales / month',
        v:
          monthly?.sales !== undefined
            ? rupeesCompact(monthly.sales)
            : undefined,
        r: monthly ? range(monthly.salesRange, true) : undefined,
        note: noMonthly,
      },
    ];
    const cw = CONTENT_W / cells.length;
    cells.forEach((c, i) => {
      const cx = X + i * cw + (i === 0 ? 0 : 14);
      if (i > 0) {
        doc
          .moveTo(X + i * cw, y)
          .lineTo(X + i * cw, y + 46)
          .lineWidth(0.6)
          .strokeColor(COLOR.hair)
          .stroke();
      }
      caps(c.k, cx, y);
      if (c.v) {
        text(c.v, cx, y + 12, 'b', 17, COLOR.ink);
        if (c.r)
          text(c.r, cx, y + 35, 'r', 7.2, COLOR.muted, { width: cw - 20 });
      } else {
        text(
          c.note,
          cx,
          y + 14,
          c.note === NA ? 'b' : 'm',
          c.note === NA ? 17 : 8.2,
          COLOR.muted,
          {
            width: cw - 20,
          },
        );
      }
    });
    y += 46 + 18;
  }

  // ── rating breakdown chart ───────────────────────────────────────────────
  {
    const rowH = 13.5;
    const rows = m.rating?.rows;
    ensure(17 + (rows ? rowH * 5 + 8 : 20));
    heading('Rating breakdown');

    if (rows && m.rating) {
      const barX = X + 28;
      const barW = 170;
      rows.forEach((row, i) => {
        const ry = y + i * rowH;
        text(String(row.star), X, ry, 's', 8.4, COLOR.ink);
        star(X + 15, ry + 4.6, 3.6, COLOR.warn);
        doc.save();
        doc.roundedRect(barX, ry + 1.5, barW, 6.5, 3.25).fill(COLOR.track);
        doc.restore();
        if (row.pct > 0) {
          const fill =
            row.star >= 4
              ? COLOR.brand
              : row.star === 3
                ? COLOR.muted
                : COLOR.warn;
          doc.save();
          doc
            .roundedRect(
              barX,
              ry + 1.5,
              Math.max((barW * row.pct) / 100, 6.5),
              6.5,
              3.25,
            )
            .fill(fill);
          doc.restore();
        }
        text(`${row.pct}%`, barX + barW + 10, ry, 's', 8.2, COLOR.ink, {
          width: 28,
        });
        text(
          row.count.toLocaleString('en-IN'),
          barX + barW + 40,
          ry,
          'r',
          8,
          COLOR.muted,
          {
            width: 42,
            align: 'right',
          },
        );
      });

      const sx = X + 318;
      if (m.rating.average !== undefined) {
        text(m.rating.average.toFixed(1), sx, y - 2, 'b', 24, COLOR.ink);
        text('out of 5', sx, y + 26, 'r', 7.8, COLOR.muted);
      }
      const lines: Array<{ v: string; t: string; c: string }> = [];
      if (m.rating.positivePct !== undefined)
        lines.push({
          v: `${m.rating.positivePct}%`,
          t: 'rated 4–5 stars',
          c: COLOR.brandDark,
        });
      if (m.rating.negativePct !== undefined)
        lines.push({
          v: `${m.rating.negativePct}%`,
          t: 'rated 1–2 stars',
          c: COLOR.warn,
        });
      lines.forEach((l, i) => {
        const ly = y + 42 + i * 14;
        text(l.v, sx, ly, 's', 9, l.c);
        text(l.t, sx + 32, ly + 0.6, 'r', 8.2, COLOR.body);
      });
      y += rowH * 5 + 16;
    } else {
      text(NA, X, y, 'b', 11, COLOR.muted);
      y += 20 + 14;
    }
  }

  // ── suggestions from the RL algorithm (language model) ───────────────────
  const keywords = m.insights?.keywords ?? [];
  const takeaways = m.insights?.takeaways ?? [];
  const tip = m.insights?.tip ?? '';

  {
    const chipH = 16;
    const gap = 5;
    const layout: Array<{ w: string; x: number; row: number; cw: number }> = [];
    let cx = 0;
    let row = 0;
    for (const word of keywords) {
      const cw = widthOf(word, 'm', 8) + 18;
      if (cx + cw > CONTENT_W && cx > 0) {
        cx = 0;
        row += 1;
      }
      layout.push({ w: word, x: cx, row, cw });
      cx += cw + gap;
    }
    const rows = keywords.length > 0 ? row + 1 : 0;
    ensure(17 + (rows > 0 ? rows * (chipH + gap) : 14));
    heading('Keywords to rank for', RL_SUGGESTED);
    if (rows === 0) {
      text(NA, X, y, 'b', 11, COLOR.muted);
      y += 14 + 14;
    } else {
      for (const c of layout) {
        const cy = y + c.row * (chipH + gap);
        doc.save();
        doc.roundedRect(X + c.x, cy, c.cw, chipH, 8.5).fill(COLOR.tint);
        doc.restore();
        text(c.w, X + c.x + 9, cy + 4.7, 'm', 8, COLOR.brandDark);
      }
      y += rows * (chipH + gap) + 14;
    }
  }

  {
    // Takeaways and the tip are one group: they move to the next page together, never the tip alone.
    const tw2 = CONTENT_W - 14;
    const heights = takeaways.map((t) => heightOf(t, 'r', 8.4, tw2, 1.5));
    const takeawaysH =
      17 +
      (takeaways.length > 0 ? heights.reduce((a, b) => a + b + 6, 0) : 14) +
      8;
    const tw3 = CONTENT_W - 40;
    const tipText = tip || NA;
    const th = heightOf(tipText, 'm', 8.8, tw3, 2);
    const tipH = 12 + 9 + 5 + th + 12;
    ensure(takeawaysH + tipH);

    heading('Key takeaways', RL_SUGGESTED);
    if (takeaways.length > 0) {
      takeaways.forEach((t, i) => {
        doc.save();
        doc.circle(X + 3, y + 4.4, 1.8).fill(COLOR.brand);
        doc.restore();
        doc
          .font('r')
          .fontSize(8.4)
          .fillColor(COLOR.body)
          .text(t, X + 14, y, { width: tw2, lineGap: 1.5 });
        y += heights[i] + 6;
      });
      y += 8;
    } else {
      text(NA, X, y, 'b', 11, COLOR.muted);
      y += 14 + 8;
    }

    doc.save();
    doc.roundedRect(X, y, CONTENT_W, tipH, 8).fill(COLOR.panel);
    doc.rect(X, y + 8, 3, tipH - 16).fill(COLOR.brand);
    doc.restore();
    caps(`Final tip · ${RL_SUGGESTED}`, X + 20, y + 12, COLOR.brandDark);
    doc
      .font('m')
      .fontSize(8.8)
      .fillColor(tip ? COLOR.ink : COLOR.muted)
      .text(tipText, X + 20, y + 26, { width: tw3, lineGap: 2 });
    y += tipH;
  }

  // ── footer on every page ─────────────────────────────────────────────────
  const { count } = doc.bufferedPageRange();
  for (let i = 0; i < count; i += 1) {
    doc.switchToPage(i);
    const fy = PAGE.h - 58;
    hline(X, X + CONTENT_W, fy, COLOR.line);
    doc
      .font('r')
      .fontSize(6.8)
      .fillColor(COLOR.muted)
      .text(FOOTER_NOTE, X, fy + 9, {
        width: CONTENT_W - 120,
        lineGap: 1.5,
      });
    const stamp = `${m.generatedOn}  ·  ${i + 1} / ${count}`;
    text(stamp, X + CONTENT_W - 110, fy + 9, 'r', 6.8, COLOR.muted, {
      width: 110,
      align: 'right',
    });
  }
}
